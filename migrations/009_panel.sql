-- Две колонки под панель управления.
--
-- 1. topics.position — порядок очереди, который владелец задаёт перетаскиванием.
--
-- До панели порядок был только неявный: по времени возврата и по номеру строки.
-- Переставить тему местами было нечем, а это первое, что хочется сделать, когда
-- в запасе три десятка тем и одна из них вдруг стала срочной.
--
-- Ноль по умолчанию сохраняет прежнее поведение: пока владелец ничего не
-- перетаскивал, темы идут в том же порядке, что и раньше.
ALTER TABLE topics ADD COLUMN position INTEGER NOT NULL DEFAULT 0;

-- 2. assets.replaced_by_owner — эту картинку поставил человек, а не модель.
--
-- Отдельной колонкой, а не отметкой в external_ref: там уже живёт признак
-- собранной обложки, и одно поле на два разных смысла означало бы, что
-- заменённую обложку невозможно собрать заново.
--
-- Нужна на экране: владелец должен видеть, какие картинки его, а какие
-- нарисованы. Иначе «перерисовать все» однажды сотрёт то, что он поставил сам.
ALTER TABLE assets ADD COLUMN replaced_by_owner INTEGER NOT NULL DEFAULT 0;
